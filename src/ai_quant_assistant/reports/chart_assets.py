"""Self-contained charts for generated reports and previously saved report.html files."""

import re
from functools import cache
from pathlib import Path

import pandas as pd
from jinja2 import Environment, FileSystemLoader

TEMPLATES = Path(__file__).parent / "templates"
STATIC = TEMPLATES.parent.parent / "web" / "static"
NAV_KEYS = ["portfolio_nav", "benchmark_nav"]
_ENV = Environment(loader=FileSystemLoader(TEMPLATES), autoescape=True)


@cache
def assets():
    vendor = STATIC / "vendor" / "lightweight-charts-5.3.0"
    return {
        "library": (vendor / "lightweight-charts.standalone.production.js").read_text("utf-8"),
        "renderer": (STATIC / "workbench-charts.js").read_text("utf-8"),
        "notices": "\n\n".join(
            (vendor / name).read_text("utf-8")
            for name in ("NOTICE.txt", "LICENSE.txt", "fancy-canvas-LICENSE.txt")
        ),
    }


def chart_rows(frame, keys):
    if frame.empty or "date" not in frame:
        return []
    data = frame.reindex(columns=["date", *keys]).copy()
    data["date"] = data["date"].astype(str).str[:10]
    for key in keys:
        data[key] = pd.to_numeric(data[key], errors="coerce").replace(
            [float("inf"), -float("inf")], None
        )
    return data.astype(object).where(data.notna(), None).to_dict("records")


def price_series(indicators, signals, orders):
    symbols = sorted(indicators.get("symbol", pd.Series(dtype=str)).dropna().astype(str).unique())
    if not symbols:
        return {}
    first_signal = str(signals.iloc[0].get("symbol")) if not signals.empty else None
    symbol = first_signal if first_signal in symbols else symbols[0]
    frame = indicators.loc[indicators["symbol"].astype(str).eq(symbol)]
    keys = [key for key in frame if re.fullmatch(r"signal_close|ma_\d+", key)]
    rows = chart_rows(frame, keys)
    markers = []

    def events(table, date_key, label, color, shape):
        if "symbol" not in table or date_key not in table:
            return
        for day in table.loc[table["symbol"].astype(str).eq(symbol), date_key].dropna():
            markers.append(
                {
                    "date": str(day)[:10],
                    "text": label,
                    "color": color,
                    "shape": shape,
                    "position": "inBar",
                }
            )

    if "action" in signals:
        events(signals[signals.action == "buy"], "signal_date", "买入信号", "#24523b", "arrowUp")
        events(signals[signals.action == "sell"], "signal_date", "卖出信号", "#b34c40", "arrowDown")
    events(orders, "planned_execution_date", "计划", "#98721b", "square")
    if "status" in orders:
        events(orders[orders.status == "executed"], "execution_date", "成交", "#356f9a", "circle")
        events(orders[orders.status != "executed"], "execution_date", "受限", "#b34c40", "square")
    dates = {row["date"] for row in rows}
    rows.extend({"date": day} for day in sorted({m["date"] for m in markers} - dates))
    colors = ["#24523b", "#a16b19", "#356f9a", "#8c5394", "#a34f48"]
    lines = [
        {
            "key": key,
            "label": "信号收盘价" if key == "signal_close" else f"MA({key[3:]})",
            "color": colors[i % len(colors)],
        }
        for i, key in enumerate(keys)
    ]
    return {
        "symbol": symbol,
        "price_adjustment": str(frame.iloc[0].get("price_adjustment", "")),
        "rows": rows,
        "lines": lines,
        "markers": markers,
    }


# Only replace chart elements generated by the historical report templates.
_OLD_CHART = re.compile(
    r'<svg\b[^>]*aria-label="(策略与基准净值曲线|策略与基准累计净值，横轴日期，纵轴累计净值|股票价格、移动平均线和交易事件)"[^>]*>.*?</svg>',
    re.S,
)


def upgrade_saved_report(path: Path):
    html = path.read_text("utf-8")
    if 'id="report-chart-data"' in html or not _OLD_CHART.search(html):
        return None

    def read(name, columns):
        csv = path.with_name(name + ".csv")
        if not csv.is_file():
            return pd.DataFrame()
        try:
            return pd.read_csv(csv, dtype=str, usecols=columns)
        except pd.errors.EmptyDataError:
            return pd.DataFrame()

    nav = chart_rows(read("daily_nav", lambda k: k in ["date", *NAV_KEYS]), NAV_KEYS)
    price = {}
    if 'aria-label="股票价格、移动平均线和交易事件"' in html:
        price = price_series(
            read(
                "indicator_series",
                lambda k: (
                    k in {"date", "symbol", "price_adjustment", "signal_close"}
                    or k.startswith("ma_")
                ),
            ),
            read("signals", lambda k: k in {"symbol", "signal_date", "action"}),
            read(
                "orders",
                lambda k: k in {"symbol", "status", "planned_execution_date", "execution_date"},
            ),
        )

    def replace(match):
        chart = "report-price" if match[1].startswith("股票") else "report-nav"
        if not (price.get("rows") if chart == "report-price" else nav):
            return match[0]  # An archived graphic may be the only surviving evidence.
        return f'<div class="report-chart" id="{chart}"></div>'

    converted = _OLD_CHART.sub(replace, html)
    if converted == html:
        return None
    html = converted
    bundle = _ENV.get_template("report-charts.html.j2").render(
        nav_rows=nav, price_chart=price, chart_assets=assets()
    )
    return html.replace("</body>", bundle + "\n</body>", 1)
